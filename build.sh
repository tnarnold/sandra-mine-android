#!/usr/bin/env bash
# Builds SandraMine.apk without Gradle:
#   cargo-ndk (sandra-core via JNI) -> aapt2 -> javac -> d8 -> zip lib/ -> zipalign -> apksigner.
# Needs: a JDK (17+), the Android SDK (build-tools, a platform), the NDK, Rust with
# cargo-ndk and the Android targets, and tnarnold/sandra-mine cloned next to this repo. See README.md.
set -euo pipefail
cd "$(dirname "$0")"

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Android/Sdk" "$HOME/Library/Android/sdk" /opt/android-sdk /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found: set ANDROID_HOME (see README)."; exit 1; }
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1 || true)"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-35\""; exit 1; }
if [ -z "${ANDROID_NDK_HOME:-}" ]; then
  ANDROID_NDK_HOME="$(ls -d "$SDK"/ndk/* 2>/dev/null | sort -V | tail -1 || true)"
fi
[ -d "${ANDROID_NDK_HOME:-}" ] || { echo "Android NDK not found. Run: sdkmanager \"ndk;27.3.13750724\""; exit 1; }
export ANDROID_NDK_HOME
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }
[ -n "${JAVA_HOME:-}" ] && export PATH="$JAVA_HOME/bin:$PATH" # d8 and apksigner run "java"
command -v cargo-ndk >/dev/null 2>&1 || { echo "cargo-ndk not found. Run: cargo install cargo-ndk"; exit 1; }
[ -d ../sandra-mine/core ] || { echo "sandra-core not found: clone https://github.com/tnarnold/sandra-mine next to this repo."; exit 1; }

# --- Settings: config.properties -> Config.java
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created config.properties: put your Bitcoin address there, then build again."
fi
prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\')"
  printf '%s' "${v:-$2}"
}
number() {
  local v; v="$(prop "$1" "$2")"
  [[ "$v" =~ ^[0-9]+$ ]] || { echo "config.properties: $1 must be a whole number (got \"$v\")" >&2; exit 1; }
  printf '%s' "$v"
}
THREADS="$(number threads 2)"
CPU="$(number cpu 50)"
PORT="$(number pool_port 21496)"

rm -rf out/gen out/classes out/*.apk out/*.dex out/res.zip && mkdir -p out/gen/io/sandramine out/classes
cat > out/gen/io/sandramine/Config.java <<EOF
package io.sandramine;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String BTC_ADDRESS = "$(prop btc_address '')";
    static final String WORKER = "$(prop worker '')";
    static final String POOL_HOST = "$(prop pool_host public-pool.io)";
    static final int POOL_PORT = $PORT;
    static final int THREADS = $THREADS;
    static final int CPU = $CPU;
    static final String LANGUAGE = "$(prop language auto)";
    static final String CURRENCY = "$(prop currency '')";
}
EOF

# --- Native: sandra-core + JNI bridge for 32-bit (most TVs) and 64-bit ARM
(cd rust && cargo ndk -t armeabi-v7a -t arm64-v8a -P 26 -o ../out/lib build --release)

# --- App
"$BT/aapt2" compile --dir app/res -o out/res.zip
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/res.zip \
  --min-sdk-version 26 --target-sdk-version 33 -A app/assets -0 ttf -0 rgb565
"$JAVAC" -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$AJ" \
  -encoding UTF-8 -d out/classes $(find app/src out/gen -name '*.java')
"$BT/d8" --release --min-api 26 --lib "$AJ" --output out $(find out/classes -name '*.class')
if command -v zip >/dev/null; then (cd out && zip -qj base.apk classes.dex && zip -qr base.apk lib)
else "${JAVA_HOME:+$JAVA_HOME/bin/}jar" -u -M -f out/base.apk -C out classes.dex -C out lib; fi
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign with your own key (created once; updates need the same key, so keep sandramine.keystore)
if [ ! -f sandramine.keystore ]; then
  "$KEYTOOL" -genkeypair -keystore sandramine.keystore -alias sandramine -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass sandramine -keypass sandramine -dname "CN=SandraMine" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks sandramine.keystore --ks-pass pass:sandramine --key-pass pass:sandramine \
  --out SandraMine.apk out/aligned.apk
echo "Built SandraMine.apk ($(du -h SandraMine.apk | cut -f1)). Install: adb install -r SandraMine.apk"
